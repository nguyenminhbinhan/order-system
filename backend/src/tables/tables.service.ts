  async lockTable(tableId: number, user?: any) {
    const table = await this.prisma.table.findUnique({ where: { id: tableId } });
    if (!table) throw new NotFoundException('Table not found');
    if (table.isLocked) {
      throw new BadRequestException('Bàn đã bị khóa rồi.');
    }

    await this.prisma.table.update({
      where: { id: tableId },
      data: { isLocked: true }
    });

    this.orderGateway.emitTableLocked({
      tableId,
      isLocked: true,
      tableName: table.name,
    });

    await this.prisma.auditLog.create({
      data: {
        userId: user?.id || null,
        action: 'LOCK_TABLE',
        tableId,
        metadata: {}
      }
    });

    return { success: true, isLocked: true };
  }

  async unlockTable(tableId: number, user?: any) {
    const table = await this.prisma.table.findUnique({ where: { id: tableId } });
    if (!table) throw new NotFoundException('Table not found');
    if (!table.isLocked) {
      throw new BadRequestException('Bàn không bị khóa.');
    }

    await this.prisma.table.update({
      where: { id: tableId },
      data: { isLocked: false }
    });

    this.orderGateway.emitTableLocked({
      tableId,
      isLocked: false,
      tableName: table.name,
    });

    await this.prisma.auditLog.create({
      data: {
        userId: user?.id || null,
        action: 'UNLOCK_TABLE',
        tableId,
        metadata: {}
      }
    });

    return { success: true, isLocked: false };
  }

  async getBillSnapshot(sessionId: string) {
    const session = await this.prisma.tableSession.findUnique({
      where: { id: sessionId }
    });
    if (!session) {
      throw new NotFoundException('Session not found');
    }
    return session.billSnapshot || null;
  }
