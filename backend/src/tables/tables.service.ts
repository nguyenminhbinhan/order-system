  async fixStuckTable(tableId: number) {
    const session = await this.prisma.tableSession.findFirst({
      where: { tableId, endedAt: null },
      include: { orders: true }
    });

    if (!session) return;

    const hasPending = session.orders.some((o: any) => o.status === 'pending_confirmation');

    if (hasPending) {
      // Force-confirm stuck pending orders before bill preview

      await this.prisma.order.updateMany({
        where: { sessionId: session.id },
        data: { status: 'confirmed' }
      });
    }
  }

  async getPreviewBill(tableId: number) {
    const session = await this.prisma.tableSession.findFirst({
      where: { tableId, endedAt: null },
      orderBy: { startedAt: 'desc' },
      include: {
        table: true,
        orders: {
          where: { status: { not: 'cancelled' } },
          include: {
            items: { include: { menuItem: true } }
          }
        }
      }
    });

    if (!session) {
      throw new BadRequestException('NO_ACTIVE_SESSION');
    }

    // Flatten all order items, EXCLUDE cancelled items, aggregate by menuItemId+note
    const itemMap = new Map<string, { name: string; price: number; quantity: number; note: string }>();

    for (const order of session.orders) {
      for (const item of order.items) {
        // ONLY ready items should appear on the bill
        if (item.status !== 'ready') continue;

        const price = Number(item.price || 0);
        const key = `${item.menuItemId}-${item.note || ''}`;

        if (itemMap.has(key)) {
          const existing = itemMap.get(key)!;
          existing.quantity += item.quantity;
        } else {
          itemMap.set(key, {
            name: item.name || item.menuItem?.name || 'Item',
            price,
            quantity: item.quantity,
            note: item.note || '',
          });
        }
      }
    }

    const items = Array.from(itemMap.values());
    const subtotal = items.reduce((sum, i) => sum + i.price * i.quantity, 0);

    await this.fixStuckTable(tableId);

    return {
      tableId,
      tableNumber: session.table?.name?.replace('Table', '').trim() || String(tableId),
      sessionId: session.id,
      startedAt: session.startedAt,
      items,
      subtotal,
      total: subtotal,
      orderCount: session.orders.length,
    };
  }

