  async checkout(tableId: number, user?: any) {
    if (!tableId) {
      throw new BadRequestException('Invalid tableId');
    }

    const transactionResult = await this.prisma.$transaction(async (tx) => {
      const session = await tx.tableSession.findFirst({
        where: { tableId, endedAt: null },
        orderBy: { startedAt: 'desc' },
        include: {
          table: true,
          orders: {
            where: { status: { not: 'cancelled' } },
            include: {
              items: { include: { menuItem: true } }
            }
          }
        }
      });

      if (!session) {
        throw new BadRequestException('NO_ACTIVE_SESSION');
      }

      if (session.orders.length === 0) {
        throw new BadRequestException('Bàn chưa có order');
      }

      // Build aggregated item list of only ready items, excluding cancelled items/orders
      const itemMap = new Map<string, { name: string; price: number; quantity: number; note: string }>();

      for (const order of session.orders) {
        for (const item of order.items) {
          if (item.status === 'ready') {
            const price = Number(item.price || 0);
            const key = `${item.menuItemId}-${item.note || ''}`;

            if (itemMap.has(key)) {
              itemMap.get(key)!.quantity += item.quantity;
            } else {
              itemMap.set(key, {
                name: item.name || item.menuItem?.name || 'Món ăn',
                price,
                quantity: item.quantity,
                note: item.note || '',
              });
            }
          }
        }
      }

      const items = Array.from(itemMap.values());
      const totalAmount = items.reduce((sum, i) => sum + i.price * i.quantity, 0);

      if (totalAmount === 0) {
        throw new BadRequestException('Chưa có món nào hoàn tất để thanh toán');
      }

      const paidAt = new Date();
      const billSnapshot = {
        tableId: session.tableId,
        tableNumber: session.table?.name?.replace('Table', '').trim() || String(session.tableId),
        tableName: session.table?.name || `Bàn ${session.tableId}`,
        sessionId: session.id,
        startedAt: session.startedAt,
        paidAt,
        items,
        subtotal: totalAmount,
        total: totalAmount,
      };

      // Close session
      await tx.tableSession.update({
        where: { id: session.id },
        data: {
          endedAt: paidAt,
          paidAt,
          totalAmount,
          billSnapshot: billSnapshot as any,
        }
      });

      // Reset Table
      await tx.table.update({
        where: { id: tableId },
        data: { status: 'empty' }
      });

      await tx.message.deleteMany({
        where: { tableId }
      });

      await tx.auditLog.create({
        data: {
          userId: user?.id || null,
          action: 'CHECKOUT',
          tableId: tableId,
          metadata: { totalAmount, sessionId: session.id }
        }
      });

      return { totalAmount, sessionId: session.id };
    }, { timeout: 20000 });

    // Use centralized gateway emission
    this.orderGateway.emitPaymentCompleted({ tableId, sessionId: transactionResult.sessionId });
    return { success: true, totalAmount: transactionResult.totalAmount, sessionId: transactionResult.sessionId };
  }

  /**
   * Create a QR payment for a table's active session.
   * Delegates to PaymentsService-compatible logic.
   */
  async createPaymentForTable(tableId: number) {
    const session = await this.prisma.tableSession.findFirst({
      where: { tableId, endedAt: null },
      orderBy: { startedAt: 'desc' },
      include: {
        table: true,
        orders: {
          where: { status: { notIn: ['cancelled'] } },
          include: { items: true }
        }
      }
    });

    if (!session) {
      throw new BadRequestException('NO_ACTIVE_SESSION');
    }

    if (session.orders.length === 0) {
      throw new BadRequestException('Bàn chưa có order');
    }

    // Calculate total of only ready items
    let subtotal = 0;
    for (const order of session.orders) {
      for (const item of order.items) {
        if (item.status === 'ready') {
          subtotal += Number(item.price || 0) * item.quantity;
        }
      }
    }

    if (subtotal === 0) {
      throw new BadRequestException('Chưa có món nào hoàn tất để thanh toán');
    }

    // Check if there's already a pending payment for this session
    const existingPayment = await this.prisma.payment.findFirst({
      where: {
        order: { sessionId: session.id },
        status: 'pending',
      }
    });

    if (existingPayment) {
      if (Number(existingPayment.amount) !== subtotal) {
        await this.prisma.payment.update({
          where: { id: existingPayment.id },
          data: { amount: subtotal }
        });
      }
      return {
        paymentId: existingPayment.id,
        amount: subtotal,
        tableId,
        sessionId: session.id,
      };
    }

    const firstOrder = session.orders[0];
    const payment = await this.prisma.payment.create({
      data: {
        order: { connect: { id: firstOrder.id } },
        method: 'bank',
        amount: subtotal,
        status: 'pending',
      }
    });

    // Update table status
    await this.prisma.table.update({
      where: { id: tableId },
      data: { status: 'needs_payment' }
    });

    this.orderGateway.server.to('service').emit('tableUpdated', tableId);

    return {
      paymentId: payment.id,
      amount: subtotal,
      tableId,
      sessionId: session.id,
    };
  }

